/**
 * Writes openapi/openapi.yaml from the routes of the stack and the Joi contracts of their handlers.
 * npm run openapi writes the file; npm run openapi:check (CI) fails when the committed file doesn't match the code
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';
import { App } from 'aws-cdk-lib/core';
import { Construct } from 'constructs';
import type { ObjectSchema, Schema } from 'joi';
import joiToJson from 'joi-to-json';
import { stringify } from 'yaml';
import { AuthType, Route, RouteAuth } from '../infra/constructs/api';
import { buildConfig } from '../infra/environments/env-builder';
import { Stage } from '../infra/environments/stage';
import type { StageConfig } from '../infra/environments/types';
import { ServiceStack } from '../infra/service-stack';
import type { ApiGatewayHandler, RequestContract } from '../src/api/types';

const PROJECT_ROOT: string = path.resolve(__dirname, '..');
const SPEC_FILE: string = path.join(PROJECT_ROOT, 'openapi', 'openapi.yaml');
const SPEC_FILE_LABEL = 'openapi/openapi.yaml';
const HEADER =
  '# Generated by tools/generate-openapi.ts from the Joi contracts of the handlers.\n' +
  '# Do not edit by hand: run `npm run openapi`.\n';
const JSON_TYPE = 'application/json';

type OpenApiObject = Record<string, unknown>;
type SecurityScheme = { name: string; definition: OpenApiObject };

const SECURITY_SCHEMES: Record<Exclude<AuthType, AuthType.NONE>, OpenApiObject> = {
  [AuthType.COGNITO]: { type: 'apiKey', in: 'header', name: 'Authorization', description: 'ID token of the user pool' },
  [AuthType.LAMBDA]: {
    type: 'apiKey',
    in: 'header',
    name: 'Authorization',
    description: 'ID token of the user pool, checked by the lambda authorizer',
  },
  [AuthType.IAM]: {
    type: 'apiKey',
    in: 'header',
    name: 'Authorization',
    description: 'The request is signed with AWS credentials (SigV4)',
    'x-amazon-apigateway-authtype': 'awsSigv4',
  },
};

function main(): void {
  /** Routes and auth don't depend on the stage. No bundling: the spec needs the routes, not the lambda code */
  const config = buildConfig(Stage.DEV);
  const app = new App({ context: { 'aws:cdk:bundling-stacks': [] } });
  const { api } = new ServiceStack(app, 'OpenApi', { config, env: { region: config.awsRegion } });

  const paths: Record<string, Record<string, OpenApiObject>> = {};
  const securitySchemes: Record<string, OpenApiObject> = {};
  const routesWithoutContract: string[] = [];

  for (const route of api.routes) {
    const contract = loadContract(route);
    if (!contract) {
      routesWithoutContract.push(
        `${route.method} /${route.path}: ${route.handler.entry} → ${route.handler.exportName}`
      );
      continue;
    }
    const scheme = toSecurityScheme(route.auth);
    if (scheme) {
      securitySchemes[scheme.name] = scheme.definition;
    }
    paths[`/${route.path}`] ??= {};
    paths[`/${route.path}`][route.method.toLowerCase()] = toOperation(route, contract, scheme);
  }

  if (routesWithoutContract.length) {
    console.error('These routes have no contract. Pass one to restApiHandler ({} for a handler without input):');
    routesWithoutContract.forEach((route) => console.error(`  - ${route}`));
    process.exit(1);
  }

  const document = {
    openapi: '3.0.3',
    info: { title: config.serviceName, version: readPackageVersion() },
    servers: Object.values(Stage).map((stage) => toServer(buildConfig(stage))),
    paths,
    components: {
      securitySchemes,
      schemas: {
        Error: { type: 'object', required: ['message'], properties: { message: { type: 'string' } } },
      },
    },
  };
  const content = HEADER + stringify(document, { lineWidth: 120, aliasDuplicateObjects: false });

  if (process.argv.includes('--check')) {
    const committed = existsSync(SPEC_FILE) ? readFileSync(SPEC_FILE, 'utf8') : '';
    if (committed !== content) {
      console.error(`${SPEC_FILE_LABEL} doesn't match the code. Run \`npm run openapi\` and commit the file`);
      process.exit(1);
    }
    console.log(`${SPEC_FILE_LABEL} matches the code`);
    return;
  }
  mkdirSync(path.dirname(SPEC_FILE), { recursive: true });
  writeFileSync(SPEC_FILE, content);
  console.log(`${SPEC_FILE_LABEL}: ${api.routes.length} routes`);
}

/** A server per stage: its custom domain (apiDomain in the stage config), otherwise the execute-api URL */
function toServer({ stage, awsRegion, apiDomain }: StageConfig): OpenApiObject {
  if (apiDomain) {
    return { url: `https://${apiDomain}`, description: stage };
  }
  return {
    url: `https://{apiId}.execute-api.${awsRegion}.amazonaws.com/${stage}`,
    description: stage,
    variables: { apiId: { default: 'api-id', description: 'The id in ApiRestApiEndpoint… of the deploy output' } },
  };
}

/** Handlers have no side effects on import: their clients get created, nothing gets called */
function loadContract({ handler }: Route): RequestContract | undefined {
  const handlerModule: Record<string, ApiGatewayHandler | undefined> = require(path.join(PROJECT_ROOT, handler.entry));
  return handlerModule[handler.exportName]?.contract;
}

function toSecurityScheme(auth: RouteAuth): SecurityScheme | undefined {
  if (auth === AuthType.NONE) {
    return undefined;
  }
  if (typeof auth === 'string') {
    return { name: auth, definition: SECURITY_SCHEMES[auth] };
  }
  return {
    name: Construct.isConstruct(auth) ? auth.node.id : 'authorizer',
    definition: { type: 'apiKey', in: 'header', name: 'Authorization', description: 'A custom authorizer' },
  };
}

function toOperation(route: Route, contract: RequestContract, scheme: SecurityScheme | undefined): OpenApiObject {
  const parameters = [...toParameters(contract.path, 'path'), ...toParameters(contract.query, 'query')];
  return {
    operationId: route.handler.exportName,
    tags: [path.basename(path.dirname(route.handler.entry))],
    security: scheme ? [{ [scheme.name]: [] }] : [],
    ...(parameters.length ? { parameters } : {}),
    ...(contract.body ? { requestBody: toRequestBody(contract.body) } : {}),
    responses: toResponses(route.auth, contract),
  };
}

/** A missing body reaches the handler as {}, so the body is required only when {} breaks the schema */
function toRequestBody(schema: Schema): OpenApiObject {
  return {
    required: Boolean(schema.validate({}).error),
    content: { [JSON_TYPE]: { schema: toSchema(schema) } },
  };
}

/** The responses that restApiHandler and API Gateway give. Success bodies are not described yet */
function toResponses(auth: RouteAuth, contract: RequestContract): OpenApiObject {
  const responses: OpenApiObject = { '200': { description: 'OK' } };
  if (contract.body || contract.query || contract.path) {
    responses['400'] = errorResponse('The request does not match the contract');
  }
  if (auth === AuthType.IAM) {
    responses['403'] = errorResponse('The request is not signed, or the caller may not invoke the route');
  } else if (auth !== AuthType.NONE) {
    responses['401'] = errorResponse('No token, or the token is not valid');
  }
  if (contract.body) {
    responses['422'] = errorResponse('The body is not valid JSON');
  }
  return responses;
}

function errorResponse(description: string): OpenApiObject {
  return { description, content: { [JSON_TYPE]: { schema: { $ref: '#/components/schemas/Error' } } } };
}

function toParameters(schema: ObjectSchema | undefined, location: 'path' | 'query'): OpenApiObject[] {
  if (!schema) {
    return [];
  }
  const { properties = {}, required = [] } = toSchema(schema) as {
    properties?: Record<string, OpenApiObject>;
    required?: string[];
  };
  return Object.entries(properties).map(([name, property]) => ({
    name,
    in: location,
    required: location === 'path' || required.includes(name),
    schema: property,
  }));
}

function toSchema(schema: Schema): OpenApiObject {
  return withoutRegexFlags(joiToJson(schema as unknown as Parameters<typeof joiToJson>[0], 'open-api'));
}

/** joi-to-json keeps the regex flags in pattern ("^[a-z]+$/u"), and OpenAPI validators reject them */
function withoutRegexFlags<T>(node: T): T {
  if (Array.isArray(node)) {
    node.forEach(withoutRegexFlags);
  } else if (node && typeof node === 'object') {
    for (const [key, value] of Object.entries(node)) {
      if (key === 'pattern' && typeof value === 'string') {
        (node as Record<string, unknown>)[key] = value.replace(/\/[dgimsuvy]+$/, '');
      } else {
        withoutRegexFlags(value);
      }
    }
  }
  return node;
}

function readPackageVersion(): string {
  return JSON.parse(readFileSync(path.join(PROJECT_ROOT, 'package.json'), 'utf8')).version;
}

main();
